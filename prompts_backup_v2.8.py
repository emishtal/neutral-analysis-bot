"""
Промпты для GigaChat API v3.0 (ДВУХПРОХОДНАЯ АРХИТЕКТУРА)
Революция: Генерация → Аудит себя
"""

def get_basic_prompt_v3(situation: str, participants: str, agreement_type: str, 
                        agreement_details: str, completion_criteria: str, 
                        what_happened: str, evidence: str, main_concern: str,
                        refinement_text: str = None) -> str:
    """
    ПРОХОД 1: Генерация базового анализа (черновик)
    Задача попроще - просто сгенерировать с обязательным полем
    """
    
    refinement_section = ""
    if refinement_text:
        refinement_section = f"\n\n**ДОПОЛНИТЕЛЬНЫЕ ФАКТЫ:**\n{refinement_text}\n"
    
    prompt = f"""🔧 ПРОМПТ v3.0 (БАЗОВЫЙ - ГЕНЕРАЦИЯ)

Роль модели

Ты — аналитик конфликтов.
Твоя задача — найти где люди по-разному понимают одни и те же слова.

⸻

Ключевой вопрос

**Какие две разные вещи стороны называли одним и тем же словом?**

⸻

ДАННЫЕ СИТУАЦИИ:

**Краткое описание:**
{situation}

**Участники:**
{participants}

**Тип договорённости:**
{agreement_type}

**Что было оговорено:**
{agreement_details}

**Критерий выполнения:**
{completion_criteria}

**Что произошло:**
{what_happened}

**Доказательства:**
{evidence}

**Что беспокоит:**
{main_concern}
{refinement_section}

⸻

ФОРМАТ АНАЛИЗА

**1. Краткое описание ситуации**

2-3 предложения.

⸻

**2. Зафиксированные факты**

Что реально произошло.

⸻

**3. Ключевое расхождение сторон**

В чём стороны не совпадают.

⸻

**4. СТРУКТУРНАЯ ПРИЧИНА КОНФЛИКТА**

**Формат:**

```
Структурная причина конфликта:

Стороны использовали одно и то же слово (или фразу),
но вкладывали в него разный смысл.

Слово / фраза: «___________»

Для стороны А это означало:
— _______________________

Для стороны Б это означало:
— _______________________

Из-за этого каждая сторона считала,
что действует правильно,
а другая — нарушает договорённость.
```

❗ **ОБЯЗАТЕЛЬНО заполни "Слово / фраза"!**

⸻

**5. Почему конфликт стал неизбежным**

1-2 абзаца.

⸻

Отвечай по-русски, простым языком.
"""
    
    return prompt


def get_audit_prompt_v3(generated_text: str) -> str:
    """
    ПРОХОД 2: Аудит собственного текста
    Модель проверяет СЕБЯ как независимый критик
    
    КЛЮЧЕВАЯ ИДЕЯ: Модель думает что это чужой текст!
    """
    
    prompt = f"""🔧 ПРОМПТ v3.0 (АУДИТ)

⚠️ Ты выступаешь как НЕЗАВИСИМЫЙ АУДИТОР.
Ты НЕ автор этого текста.

⸻

ТЕКСТ ДЛЯ ПРОВЕРКИ:

---
{generated_text}
---

⸻

ПРОВЕРЬ ТЕКСТ ПО ПРАВИЛАМ:

✅ **Правило 1: Конкретное слово/фраза**

В пункте "Структурная причина" ОБЯЗАТЕЛЬНО должно быть:
• Одно конкретное слово или фраза в кавычках
• Два разных смысла этого слова

❌ Если нет конкретного слова → ДОБАВЬ его.

⸻

❌ **Правило 2: Запрещённые формулировки**

СТРОГО ЗАПРЕЩЕНО:
• "какая информация считается важной"
• "отсутствие критериев"
• "не определена ответственность"
• "параметры", "механизмы", "форматы"

❌ Если такие есть → ЗАМЕНИ на конкретное слово.

⸻

❌ **Правило 3: Никаких советов**

ЗАПРЕЩЕНО:
• "следует договориться"
• "нужно определить"
• "рекомендуется"
• "должен"

❌ Если такие есть → УДАЛИ или ЗАМЕНИ.

⸻

✅ **Правило 4: Структурные точки**

Должны быть УТВЕРЖДЕНИЯМИ, а НЕ ВОПРОСАМИ.

❌ Неправильно:
"Какая форма ведения записей?"
"Кто несёт ответственность?"

✅ Правильно:
"Что именно означает «[слово]»"
"В какой момент обязательство считается выполненным"

⸻

ТВОЯ ЗАДАЧА:

1. Проверь текст по всем 4 правилам
2. Если фрагмент корректен → оставь без изменений
3. Если есть нарушения → исправь ТОЛЬКО их
4. Сохрани стиль, структуру, объём

⚠️ НЕ переписывай весь текст заново!
⚠️ Исправляй только проблемные места!

⸻

Отвечай по-русски, простым языком.
"""
    
    return prompt


def get_extended_prompt_v3(audited_basic: str) -> str:
    """
    ПРОХОД 3: Расширенный анализ
    Работает с УЖЕ ПРОВЕРЕННЫМ базовым анализом
    """
    
    prompt = f"""🔧 ПРОМПТ v3.0 (РАСШИРЕННЫЙ)

⚠️ Расширенный анализ НЕ ИЩЕТ НОВЫЕ ПРИЧИНЫ.
Он работает с УЖЕ НАЙДЕННОЙ И ПРОВЕРЕННОЙ причиной.

⸻

ПРОВЕРЕННЫЙ БАЗОВЫЙ АНАЛИЗ:

---
{audited_basic}
---

⸻

Из базового анализа (пункт 4) возьми:
• Слово / фраза
• Смысл стороны А
• Смысл стороны Б

Ты ОБЯЗАН использовать ИМЕННО ИХ!

⸻

ФОРМАТ ОТВЕТА

**Пункты 1-5 - скопируй из базового анализа**

⸻

**6. Нейтральный протокол**

```
Между сторонами существовала договорённость,
в которой использовалось слово «[слово из пункта 4]».

При этом стороны вкладывали в него разный смысл.

Сторона А понимала «[слово]» как [смысл А].
Сторона Б понимала «[слово]» как [смысл Б].

Из-за этого каждая сторона считала,
что действует в рамках договорённости,
а действия другой стороны воспринимала
как её нарушение.
```

❌ Никаких советов, "следует", "нужно"!

⸻

**7. Структурные точки конфликта**

```
Конфликт стал возможен, потому что не было определено:

— Что именно означает «[слово из пункта 4]»

— В какой момент действия считаются
  соответствующими договорённости

— При каких условиях ожидания одной стороны
  становятся обязательными для другой
```

❌ НЕ используй вопросы!
✅ Только утверждения про слово из пункта 4!

⸻

Отвечай по-русски, простым языком.
"""
    
    return prompt


# Пример использования в боте:

def analyze_conflict_v3(situation_data: dict, tier: str = "basic"):
    """
    Двухпроходный анализ v3.0
    """
    
    # ПРОХОД 1: Генерация базового (черновик)
    basic_prompt = get_basic_prompt_v3(**situation_data)
    basic_draft = gigachat.generate(basic_prompt)
    
    # ПРОХОД 2: Аудит себя (модель проверяет свой текст)
    audit_prompt = get_audit_prompt_v3(basic_draft)
    basic_final = gigachat.generate(audit_prompt)
    
    if tier == "basic":
        return basic_final
    
    # ПРОХОД 3: Расширенный (если нужно)
    extended_prompt = get_extended_prompt_v3(basic_final)
    extended_final = gigachat.generate(extended_prompt)
    
    return extended_final
