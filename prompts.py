"""
Промпты для GigaChat API - ФИНАЛЬНАЯ ВЕРСИЯ
Базовый: v2.8 (1 запрос)
Расширенный: v2.8 + v3.0 аудит (2 запроса)
"""

def get_basic_prompt(situation: str, participants: str, agreement_type: str, 
                     agreement_details: str, completion_criteria: str, 
                     what_happened: str, evidence: str, main_concern: str,
                     refinement_text: str = None) -> str:
    """
    Базовый анализ (49₽) - v2.8
    1 запрос к API
    """
    
    refinement_section = ""
    if refinement_text:
        refinement_section = f"\n\n**ДОПОЛНИТЕЛЬНЫЕ ФАКТЫ ОТ ПОЛЬЗОВАТЕЛЯ:**\n{refinement_text}\n"
    
    prompt = f"""🔧 ПРОМПТ v2.8 (БАЗОВЫЙ)

Роль модели

Ты — аналитик конфликтов и договорённостей.
Твоя задача — найти не «кто прав», а где именно люди по-разному понимают одни и те же слова.

Ты НЕ даёшь советов,
НЕ предлагаешь решений,
НЕ оцениваешь поведение сторон.

⸻

Ключевой принцип (ОБЯЗАТЕЛЬНО)

Перед тем как писать анализ, задай себе вопрос:

**Какие две разные вещи стороны называли одним и тем же словом или фразой?**

Если ты не можешь указать конкретное слово или фразу —
анализ считается НЕВЫПОЛНЕННЫМ.

⸻

СТРОГО ЗАПРЕЩЕНО

**Абстрактные формулировки:**
❌ «какая информация считается важной»
❌ «отсутствие критериев»
❌ «не определена ответственность»

**Процедуры и советы:**
❌ «следует договориться»
❌ «нужно определить»
❌ «рекомендуется использовать»

**Бюрократический язык:**
❌ «параметры», «механизмы», «форматы», «процессы»

⸻

ДАННЫЕ СИТУАЦИИ:

**Краткое описание:**
{situation}

**Участники:**
{participants}

**Тип договорённости:**
{agreement_type}

**Что было оговорено:**
{agreement_details}

**Критерий выполнения:**
{completion_criteria}

**Что произошло фактически:**
{what_happened}

**Доказательства:**
{evidence}

**Что беспокоит:**
{main_concern}
{refinement_section}

⸻

ФОРМАТ АНАЛИЗА (ОБЯЗАТЕЛЬНЫЙ)

**1. Краткое описание ситуации**

Коротко, бытовым языком. Без оценок.
2-3 предложения.

⸻

**2. Зафиксированные факты**

Только то, что реально произошло.
Без интерпретаций.

⸻

**3. Ключевое расхождение сторон**

Опиши, в чём именно стороны не совпадают в понимании происходящего.

⸻

**4. ⭐ СТРУКТУРНАЯ ПРИЧИНА КОНФЛИКТА** (ГЛАВНЫЙ ПУНКТ)

❗ Ответь на контрольный вопрос!

**Формат СТРОГО ТАКОЙ:**

```
Структурная причина конфликта:

Стороны использовали одно и то же слово (или фразу),
но вкладывали в него разный смысл.

Слово / фраза: «___________»

Для стороны А это означало:
— _______________________

Для стороны Б это означало:
— _______________________

Из-за этого каждая сторона считала,
что действует правильно,
а другая — нарушает договорённость.
```

❗ **ОБЯЗАТЕЛЬНО заполни поле "Слово / фраза"!**
Если ты не указал конкретное слово или фразу — пункт НЕ засчитан.

**ПРИМЕРЫ ПРАВИЛЬНЫХ ФОРМУЛИРОВОК:**

✅ Слово / фраза: «вести планы»

Для жены это означало:
— заранее составлять подробный список всех дел на неделю

Для мужа это означало:
— спонтанно сообщать о возникающих делах

✅ Слово / фраза: «вести записи»

Для жены это означало:
— составлять подробные еженедельные календари на бумаге

Для мужа это означало:
— делать быстрые заметки в памяти или телефоне

✅ Слово / фраза: «печать и ламинирование»

Для заказчика это означало:
— единый комплекс услуг

Для исполнителя это означало:
— две отдельные услуги

⸻

**5. Почему конфликт стал неизбежным**

Опиши простым языком, как именно разные смыслы привели к столкновению ожиданий.

1-2 абзаца.

⸻

КРИТЕРИЙ КАЧЕСТВА

Хороший анализ — это когда человек после прочтения говорит:

**«Теперь понятно, где именно мы по-разному понимали одно и то же»**

Если этого нет — анализ не удался.

⸻

Отвечай по-русски, простым языком.
"""
    
    return prompt


def get_extended_prompt(situation: str, participants: str, agreement_type: str,
                       agreement_details: str, completion_criteria: str,
                       what_happened: str, evidence: str, main_concern: str,
                       refinement_text: str = None,
                       user_name: str = None, user_age: int = None, user_gender: str = None,
                       basic_analysis: str = None) -> str:
    """
    Расширенный анализ (99₽) - v2.8
    Генерирует черновик расширенного анализа
    Потом будет проверен аудитом v3.0
    """
    
    refinement_section = ""
    if refinement_text:
        refinement_section = f"\n\n**ДОПОЛНИТЕЛЬНЫЕ ФАКТЫ:**\n{refinement_text}\n"
    
    prompt = f"""🔧 ПРОМПТ v2.8 (РАСШИРЕННЫЙ - ГЕНЕРАЦИЯ)

⚠️ ВАЖНОЕ ПРАВИЛО

Расширенный анализ НЕ ИЩЕТ НОВЫЕ ПРИЧИНЫ.
Он РАБОТАЕТ ТОЛЬКО с уже найденной структурной причиной из базового разбора.

❗ Запрещено:
• менять слово / фразу
• вводить новые причины
• пересматривать тип ситуации

Ты ОБЯЗАН использовать УЖЕ НАЙДЕННОЕ.

⸻

БАЗОВЫЙ АНАЛИЗ:

{basic_analysis if basic_analysis else '[Базовый анализ будет предоставлен]'}

⸻

Из базового анализа (пункт 4) возьми:
• Слово / фраза
• Смысл стороны А
• Смысл стороны Б

Ты ОБЯЗАН использовать ИМЕННО ИХ!

⸻

ДАННЫЕ СИТУАЦИИ:

**Краткое описание:**
{situation}

**Участники:**
{participants}

**Что было оговорено:**
{agreement_details}

**Что произошло:**
{what_happened}
{refinement_section}

⸻

ФОРМАТ ОТВЕТА

**Пункты 1-5 - скопируй из базового анализа идентично!**

⸻

**6. Нейтральный протокол для передачи другой стороне**

❗ Используй слово/фразу ИЗ ПУНКТА 4 базового анализа!

**Формат СТРОГО ТАКОЙ:**

```
Между сторонами существовала договорённость, 
в которой использовалось слово «[слово из пункта 4]».

При этом стороны вкладывали в него разный смысл.

Сторона А понимала «[слово]» как [смысл А из пункта 4].

Сторона Б понимала «[слово]» как [смысл Б из пункта 4].

Из-за этого каждая сторона считала, 
что действует в рамках договорённости,
а действия другой стороны воспринимала 
как её нарушение.
```

❌ СТРОГО ЗАПРЕЩЕНО:
• Советы
• Слова «следует», «должен», «нужно»
• Процедуры
• Новые причины

⸻

**7. Структурные точки конфликта**

❗ Используй ТОЛЬКО слово/фразу из пункта 4!

❗ СТРОГО НЕ В ВОПРОСАХ
❗ СТРОГО ЧЕРЕЗ УТВЕРЖДЕНИЯ

**Формат СТРОГО ТАКОЙ:**

```
Конфликт стал возможен, потому что не было определено:

— Что именно означает «[слово из пункта 4]»

— В какой момент действия считаются 
  соответствующими договорённости

— При каких условиях ожидания одной стороны 
  становятся обязательными для другой
```

❌ СТРОГО ЗАПРЕЩЕНО:
• Вопросы: «Какая форма?», «Какие правила?», «Кто должен?»
• Процедуры: «каким образом», «механизм»
• Новые слова (только из пункта 4!)

✅ ТОЛЬКО утверждения про УЖЕ НАЙДЕННОЕ слово!

⸻

Отвечай по-русски, простым языком.
"""
    
    return prompt


def get_extended_audit_prompt(extended_draft: str) -> str:
    """
    Аудит расширенного анализа - v3.0
    Проверяет черновик и исправляет ошибки форматирования
    """
    
    prompt = f"""🔧 ПРОМПТ v3.0 (АУДИТ РАСШИРЕННОГО)

⚠️ Ты выступаешь как НЕЗАВИСИМЫЙ АУДИТОР.
Ты НЕ автор этого текста.

⸻

ТЕКСТ ДЛЯ ПРОВЕРКИ:

---
{extended_draft}
---

⸻

ПРОВЕРЬ ТЕКСТ ПО ПРАВИЛАМ:

✅ **Правило 1: Конкретное слово/фраза**

В пункте "Структурная причина" (пункт 4) ОБЯЗАТЕЛЬНО должно быть:
• Одно конкретное слово или фраза в кавычках
• Два разных смысла этого слова

❌ Если нет конкретного слова → это КРИТИЧЕСКАЯ ошибка, но не меняй пункты 1-5!

⸻

❌ **Правило 2: Запрещённые формулировки в структурных точках (пункт 7)**

СТРОГО ЗАПРЕЩЕНЫ ВОПРОСЫ:
• "Какая форма ведения записей является приемлемой?"
• "Кто несёт ответственность за информирование?"
• "Какие критерии считаются достаточными?"
• "Какой объём информации считать необходимым?"
• "Где проходит граница между..."

❌ Если такие ВОПРОСЫ есть → ЗАМЕНИ на УТВЕРЖДЕНИЯ.

✅ ПРАВИЛЬНО (утверждения):
• "Что именно означает «[слово из пункта 4]»"
• "В какой момент планы считаются согласованными"
• "При каких условиях один партнёр обязан учитывать планы другого"

⸻

❌ **Правило 3: Никаких советов**

ЗАПРЕЩЕНО в пунктах 6 и 7:
• "следует договориться"
• "нужно определить"
• "рекомендуется"
• "должен"

❌ Если такие есть → УДАЛИ или ЗАМЕНИ на нейтральные формулировки.

⸻

✅ **Правило 4: Использование слова из пункта 4**

Пункты 6 и 7 ОБЯЗАНЫ использовать ИМЕННО слово/фразу из пункта 4.

❌ Если используется ДРУГОЕ слово → ИСПРАВЬ на слово из пункта 4.

⸻

ТВОЯ ЗАДАЧА:

1. Проверь пункт 7 (Структурные точки конфликта)
2. Если там ВОПРОСЫ → замени на УТВЕРЖДЕНИЯ
3. Если есть советы → удали
4. Если используется не то слово → исправь на слово из пункта 4
5. Сохрани остальной текст БЕЗ ИЗМЕНЕНИЙ

⚠️ НЕ переписывай весь текст заново!
⚠️ Исправляй ТОЛЬКО пункт 7 если там вопросы!
⚠️ Пункты 1-5 оставь БЕЗ ИЗМЕНЕНИЙ!

⸻

**ПРИМЕР ИСПРАВЛЕНИЯ:**

Было (НЕПРАВИЛЬНО):
```
Структурные точки конфликта:
1. Какая форма фиксации планов является обязательной?
2. Кто несёт ответственность за информирование?
3. Какие критерии считаются достаточными?
```

Стало (ПРАВИЛЬНО):
```
Конфликт стал возможен, потому что не было определено:
— Что именно означает «вести записи» — 
  календарь на бумаге или заметки в телефоне
— В какой момент планы считаются согласованными
— При каких условиях один партнёр обязан учитывать планы другого
```

⸻

Отвечай по-русски, простым языком.
"""
    
    return prompt
