"""
Состояния диалога бота
State machine для протокола вопросов
"""

from enum import IntEnum


class States(IntEnum):
    """Состояния разговора"""
    
    # Начальные состояния
    INTRO = 0                # Приветствие и объяснение
    
    # Протокол вопросов
    CONTEXT = 1              # Вопрос 1: Контекст ситуации
    PARTICIPANTS = 2         # Вопрос 2: Участники конфликта
    AGREEMENT_TYPE = 3       # Вопрос 3: Тип договоренности
    AGREEMENT_TEXT = 4       # Вопрос 4: Суть договоренности
    FACTS = 5                # Вопрос 5: Что произошло фактически
    EVIDENCE = 6             # Вопрос 6: Доказательства
    CONCERN = 7              # Вопрос 7: Что беспокоит
    
    # Завершающие состояния
    SUMMARY = 8              # Итоговая сводка
    PAYMENT = 9              # Выбор тарифа и оплата
    ANALYSIS = 10            # Генерация анализа
    RESULT = 11              # Показ результата
